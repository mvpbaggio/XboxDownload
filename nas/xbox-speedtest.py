        # 残留检测: uci 里同一域名挂多个 IP(v2.3.3 之前"只切首域名"时代的遗留), dnsmasq 行为不确定;
        # 组内各域名指向不一致则是"切了一半"的现场 —— 这两种都要在日志里说出来, 不能悄悄取一个当真相
        multi = {d: v for d, v in seen.items() if len(v) > 1}
