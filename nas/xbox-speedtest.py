        # 切换分支漏当前 IP、st_cur==0 分支漏冠军 —— 漏了就是重测 3 轮(0.75GiB), 而且进热备名单的是
        # **第二次**那个抖动值(Cn2 单次差 4 倍), 第二次返回 0 时该成员直接从名单静默消失。
        # 逐个打补丁已经漏过两次(C38b 只查"传了 known=" 这个语法事实, 所以全绿也拦不住),
