    # 流量账: 2026-11-06 NAS 网卡计数器实测一轮全量收 9.58GiB, 此前没人算过也没人看过。
    # 稳态每次 256MiB × 3 轮 × 每个**实际开测的节点**, 是这轮流量的绝对大头, 必须打在日志里可核对。
    # v2.3.9: 原来打 "× STEADY_CAND_MAX 候选"(= 4×3×256MiB = 3GiB/组), 而真机每组 4.02GiB ——
