    # 结束那一刻标记已经过期 3405s —— 比整个冷却窗口还长, 下一小时必然放行, 等于没有冷却。
    # 仍是同一个 mark_retest(单写者不变); 中途异常退出时开头那次标记留在原地, 退化成"从开始算"。
